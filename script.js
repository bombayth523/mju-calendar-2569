let currentSem = 'prep';
let currentView = 'category';

function render() {
  const container = document.getElementById('main-content');
  const semData = semesters[currentSem];
  
  let html = `
    <div class="semester-hero">
      <div>
        <div class="hero-title">${semData.title}</div>
        <div class="hero-range">${semData.range}</div>
      </div>
      <div class="hero-chips">
        ${semData.chips.map(c => `<span class="hero-chip">${c}</span>`).join('')}
      </div>
    </div>
  `;

  const filteredEvents = events.filter(ev => ev.sem === currentSem);

  if (currentView === 'date') {
    const sorted = [...filteredEvents].sort((a, b) => a.sort.localeCompare(b.sort));
    html += `<div class="timeline">${sorted.map(ev => renderEvent(ev)).join('')}</div>`;
  } else {
    // Group by group name
    const groups = [];
    filteredEvents.forEach(ev => {
      let g = groups.find(x => x.name === ev.group);
      if (!g) {
        g = { name: ev.group, cat: ev.cat, icon: ev.icon, items: [] };
        groups.push(g);
      }
      g.items.push(ev);
    });

    groups.forEach(g => {
      html += `
        <div class="section-group">
          <div class="section-heading ${g.cat}">
            <div class="section-icon">${g.icon}</div>
            <span class="section-heading-text">${g.name}</span>
          </div>
          <div class="timeline">${g.items.map(ev => renderEvent(ev)).join('')}</div>
        </div>
      `;
    });
  }

  container.innerHTML = html;

  // Trigger animations
  const items = container.querySelectorAll('.timeline-item');
  items.forEach((item, i) => {
    item.style.animationDelay = `${i * 0.04}s`;
  });
}

function renderEvent(ev) {
  return `
    <div class="timeline-item">
      <div class="event-card ${ev.highlight ? 'highlight' : ''}">
        <div class="event-info">
          <div class="event-title">${ev.title}</div>
          ${ev.note ? `<div class="event-note">${ev.note}</div>` : ''}
        </div>
        <div class="event-date-block">
          <div class="event-date">${ev.date}</div>
          ${ev.day ? `<div class="event-day">${ev.day}</div>` : ''}
          ${ev.range ? `<div class="date-range">${ev.range}</div>` : ''}
        </div>
      </div>
    </div>
  `;
}

function switchTab(id, btn) {
  currentSem = id;
  document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');
  render();
  
  // Scroll to top of content
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function changeView(type) {
  currentView = type;
  document.getElementById('btn-cat').classList.toggle('active', type === 'category');
  document.getElementById('btn-date').classList.toggle('active', type === 'date');
  render();
}

// Initial render
window.onload = render;
